import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE??'playwright');
const [account]=JSON.parse(await readFile('.local-demo-accounts.json','utf8'));
const base='http://127.0.0.1:5173';
const browser=await chromium.launch({headless:true,channel:'chrome'});
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
  const page=await context.newPage();page.setDefaultTimeout(15000);
  assert.equal((await context.request.post(`${base}/api/auth/login`,{headers:{origin:base},data:{email:account.email,password:account.password,expectedRole:'customer'}})).status(),200);
  const materials=await (await context.request.get(`${base}/api/materials`)).json();
  const reports=await (await context.request.get(`${base}/api/reports`)).json();
  const projects=await (await context.request.get(`${base}/api/projects`)).json();
  const project=projects.find(item=>reports.placements.some(placement=>placement.projectId===item.id));
  const completedPlacement=reports.placements.find(placement=>placement.status==='completed');
  assert.ok(project);assert.ok(completedPlacement);
  assert.ok(materials.length);assert.ok(materials.every(material=>Number.isInteger(material.number)));
  await page.goto(`${base}/customer/materials`);
  await page.getByText(`№${materials[0].number}`,{exact:false}).first().waitFor().catch(()=>{});
  await page.getByText(materials[0].title,{exact:true}).first().click();
  await page.getByText(`Материал №${materials[0].number}`,{exact:true}).waitFor();
  await page.goto(`${base}/customer/reports`);
  await page.getByRole('heading',{name:'Отчеты',exact:true}).waitFor();
  await page.getByRole('button',{name:'Все проекты',exact:true}).click();
  await page.getByRole('option',{name:project.name,exact:true}).click();
  await page.getByRole('button',{name:'Отчет по проекту',exact:true}).click();
  const createDialog=page.getByRole('dialog',{name:'Отчет по проекту'});
  await createDialog.getByRole('button',{name:project.name,exact:true}).waitFor();
  await createDialog.getByRole('button',{name:'Отмена',exact:true}).click();
  const rows=page.locator('tbody tr');assert.ok(await rows.count()>0);
  await rows.first().click();
  await page.getByRole('heading',{name:'Отчет по размещению',exact:true}).waitFor();
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Скачать отчет',exact:true}).click()]);
  assert.match(download.suggestedFilename(),/placement-\d+\.pdf/);
  await download.saveAs('/tmp/axioma-placement-report.pdf');
  await page.goto(`${base}/customer/reports`);
  const [csv]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Скачать таблицу',exact:true}).click()]);
  assert.equal(csv.suggestedFilename(),'placements.csv');
  await page.goto(`${base}/customer/projects`);
  await page.getByText(project.name,{exact:true}).first().click();
  const reportButton=page.getByRole('button',{name:'Отчет',exact:true});
  await reportButton.waitFor();assert.equal(await reportButton.isEnabled(),true);
  await reportButton.click();
  await page.getByRole('heading',{name:'Отчет по проекту',exact:true}).waitFor();
  await page.getByRole('button',{name:'Изменить период',exact:true}).click();
  const periodDialog=page.getByRole('dialog',{name:'Изменить период отчета'});
  await periodDialog.getByText(project.name,{exact:true}).waitFor();
  assert.match(page.url(),/\/customer\/project-report/);
  await periodDialog.getByRole('button',{name:'Отмена',exact:true}).click();
  await page.reload();
  await page.getByRole('heading',{name:'Отчет по проекту',exact:true}).waitFor();
  const [projectDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Скачать отчет',exact:true}).click()]);
  assert.match(projectDownload.suggestedFilename(),/project-report-\d+\.pdf/);
  await projectDownload.saveAs('/tmp/axioma-project-report.pdf');
  const orderPage=await context.newPage();orderPage.setDefaultTimeout(15000);
  await orderPage.goto(`${base}/customer/order-completed-detail?order=${encodeURIComponent(completedPlacement.id)}`);
  await orderPage.getByRole('button',{name:'Открыть отчет',exact:true}).click();
  await orderPage.getByRole('heading',{name:'Отчет по размещению',exact:true}).waitFor();
  await orderPage.reload();
  await orderPage.getByRole('heading',{name:'Отчет по размещению',exact:true}).waitFor();
  await page.screenshot({path:'/tmp/axioma-reports.png',fullPage:true});
  await context.close();
  console.log('Material numbers, project report shortcut and branded PDF downloads verified');
} finally {await browser.close();}
